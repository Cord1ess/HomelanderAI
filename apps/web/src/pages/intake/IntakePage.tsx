/**
 * Intake form — data entry with the client sitting opposite.
 *
 * ONE scrolling page, submitted once. NOT a wizard: operators jump around and
 * clients correct themselves, so nothing may be lost between steps.
 *
 * The form is **model-driven** (see docs/INTAKE_FORM.md): the operator picks
 * which model arms apply from a vertical checkbox menu ("click all that
 * applicable"). Each selected model pops out a panel with:
 *   - its own file upload (which report to attach), and
 *   - its risk-factor fields.
 *
 * A **face photo** for identification is captured in the Applicant section. It
 * is stored against the applicant and is NEVER a model input. Section 1 is a
 * two-column grid: the face photo on the left, and the client's **name, phone,
 * date of birth and sex** on the right.
 *
 * The **reference** is **generated by the database** (`applicants_ref_seq` →
 * `HL-<seq>` on `applicants.external_ref`), so the operator never types it. The
 * field is read-only; when the backend + DB are connected we fetch a preview
 * (`GET /api/applications/reference`), otherwise it reads "assigned on submit"
 * and the real value comes back in the confirmation.
 *
 * Sections: 1 · Applicant · 2 · Coverage · 3 · Models.
 *
 * Submit is disabled until: name + phone set (1), coverage type/amount set (2),
 * and at least one model selected with its required report attached (3). The
 * identity photo is **not** required — it is biometric data no model reads, so
 * demanding it would collect the most sensitive thing on the form for no gain.
 *
 * Submits multipart to `POST /api/applications`: the applicant, coverage,
 * `models_requested` and the per-model `declared_history` as one JSON field,
 * with each upload paired to the model arm that reads it. The database assigns
 * `external_ref`, and the reference shown in the confirmation is the one it
 * returned — never a client-side guess.
 */

type Scalar = string | boolean | number | string[] | null

interface ModelValues {
  [key: string]: Scalar
}

type SimpleField =
  | { kind: 'checkbox'; key: string; label: string }
  | { kind: 'select'; key: string; label: string; data: string[]; placeholder?: string }
  | { kind: 'number'; key: string; label: string; description?: string }

/**
 * File-type filters, as MIME-type keys with extensions in the value array.
 *
 * The shape matters. react-dropzone validates the **key** as a MIME type and
 * silently drops any entry whose key is not one, warning to the console. Passing
 * an array of bare extensions (`['.dcm', '.png']`) leaves an empty accept object
 * — which disables filtering entirely and accepts every file type.
 *
 * `.dcm` has no registered browser MIME type and most browsers report an empty
 * string for it, so the extension in the value array is what actually matches.
 */
type AcceptMap = Record<string, string[]>

const DICOM: AcceptMap = { 'application/dicom': ['.dcm'] }
const PHOTO: AcceptMap = { 'image/png': ['.png'], 'image/jpeg': ['.jpg', '.jpeg'] }
const DOCUMENT: AcceptMap = { 'application/pdf': ['.pdf'], 'text/plain': ['.txt'] }
const ECG_EXPORT: AcceptMap = { 'text/csv': ['.csv'], 'text/plain': ['.txt', '.tsv'] }

interface ModelDef {
  id: string
  label: string
  modality: string
  upload: { category: string; accept: AcceptMap; instruction: string } | null
  fields: SimpleField[]
}

