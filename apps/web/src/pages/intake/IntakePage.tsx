const MAX_FILE_BYTES = 50 * 1024 * 1024
const MAX_FACE_BYTES = 10 * 1024 * 1024

interface IntakeForm {
  reference: string
  name: string
  phone: string
  dob: string
  sex: string | null
  coverageType: string | null
  coverageAmount: number | null
  policyTerm: string | null
  selectedModels: string[]
  modelFields: Record<string, ModelValues>
}

interface EvidenceFile {
  id: string
  name: string
  size: number
  fileType: string
}

function formatSize(b: number) {
  if (b < 1024) return `${b} B`
  if (b < 1024 * 1024) return `${(b / 1024).toFixed(0)} KB`
  return `${(b / (1024 * 1024)).toFixed(1)} MB`
}

function bool(v: Scalar | undefined) {
  return v === true
}

export function IntakePage() {
  const form = useForm<IntakeForm>({
    initialValues: {
      reference: '',
      name: '',
      phone: '',
      dob: '',
      sex: null,
      coverageType: null,
      coverageAmount: null,
      policyTerm: null,
      selectedModels: [],
      modelFields: {},
    },
  })

  const [modelFiles, setModelFiles] = useState<Record<string, EvidenceFile[]>>({})
  const [facePhoto, setFacePhoto] = useState<File | null>(null)
  const [facePreview, setFacePreview] = useState<string | null>(null)
  const [rejectNote, setRejectNote] = useState<Record<string, string | null>>({})
  const [submitting, setSubmitting] = useState(false)
  const [submitted, setSubmitted] = useState(false)

  // The reference is GENERATED BY THE DATABASE (applicants_ref_seq, HL-<seq>),
  // so the operator never types it. When the backend + DB are up we fetch a
  // preview to show in the read-only field; when they are not, the field shows
  // "assigned on submit" and the real value comes back in the confirmation.
  useEffect(() => {
    let cancelled = false
    fetch('/api/applications/reference', { method: 'GET' })
      .then((r) => (r.ok ? r.json() : null))
      .then((d) => {
        if (cancelled) return
        if (d?.reference) form.setFieldValue('reference', d.reference)
      })
      .catch(() => {
        /* DB not connected — the reference is assigned at submit instead. */
      })
    return () => {
      cancelled = true
    }
  }, [form])

  const toggleSet = (modelId: string, key: string, value: string) => {
    const block = (form.values.modelFields[modelId]?.[key] as string[]) ?? []
    const next = block.includes(value)
      ? block.filter((v) => v !== value)
      : [...block, value]
    setField(modelId, key, next)
  }

  const setField = (modelId: string, key: string, value: Scalar) => {
    form.setFieldValue('modelFields', {
      ...form.values.modelFields,
      [modelId]: { ...(form.values.modelFields[modelId] ?? {}), [key]: value },
    })
  }

  const toggleModel = (id: string) => {
    const has = form.values.selectedModels.includes(id)
    form.setFieldValue(
      'selectedModels',
      has
        ? form.values.selectedModels.filter((m) => m !== id)
        : [...form.values.selectedModels, id],
    )
  }

  const selected = MODELS.filter((m) => form.values.selectedModels.includes(m.id))

  const addModelFiles = (modelId: string, dropped: File[], fileType: string) => {
    setRejectNote((p) => ({ ...p, [modelId]: null }))
    const added: EvidenceFile[] = dropped.map((f) => ({
      id: crypto.randomUUID(),
      name: f.name,
      size: f.size,
      fileType,
    }))
    setModelFiles((prev) => ({ ...prev, [modelId]: [...(prev[modelId] ?? []), ...added] }))
  }

  const addModelReject = (modelId: string, rejects: { file: File }[]) => {
    const tooBig = rejects.some((r) => r.file.size > MAX_FILE_BYTES)
    setRejectNote((p) => ({
      ...p,
      [modelId]: tooBig
        ? 'File rejected — the 50 MB limit was exceeded.'
        : 'File rejected — check the accepted type for this model.',
    }))
  }

  const removeModelFile = (modelId: string, id: string) =>
    setModelFiles((prev) => ({
      ...prev,
      [modelId]: (prev[modelId] ?? []).filter((f) => f.id !== id),
    }))

  const setFace = (file: File | null) => {
    if (facePreview) URL.revokeObjectURL(facePreview)
    setFacePhoto(file)
    setFacePreview(file ? URL.createObjectURL(file) : null)
  }

  const addFacePhoto = (dropped: File[]) => {
    setRejectNote((p) => ({ ...p, face: null }))
    if (dropped.length === 0) return
    setFace(dropped[0])
  }

  const addFaceReject = (rejects: { file: File }[]) => {
    const tooBig = rejects.some((r) => r.file.size > MAX_FACE_BYTES)
    setRejectNote((p) => ({
      ...p,
      face: tooBig
        ? 'Face photo rejected — the 10 MB limit was exceeded.'
        : 'Face photo rejected — use a .png or .jpg image.',
    }))
  }

  const modelHasUpload = (m: ModelDef) => (modelFiles[m.id] ?? []).length > 0

  /**
   * "Previously treated for TB" ticked but the follow-up left blank would be
   * sent as null and read downstream as "did not complete" — silently scoring
   * the applicant 25 points higher than an answered "yes" would. Require it.
   */
  const tbFollowUpAnswered = (() => {
    if (!form.values.selectedModels.includes('cxr_lung')) return true
    const values = form.values.modelFields.cxr_lung
    if (!bool(values?.prior_tb)) return true
    return (
      values?.prior_tb_treatment_completed === 'yes' ||
      values?.prior_tb_treatment_completed === 'no'
    )
  })()

  const modelsSectionComplete =
    selected.length > 0 &&
    selected.every((m) => m.upload === null || modelHasUpload(m)) &&
    tbFollowUpAnswered

  const sections = [
    Boolean(form.values.name.trim()) &&
      Boolean(form.values.phone.trim()) &&
      Boolean(facePhoto),
    Boolean(form.values.coverageType) && (form.values.coverageAmount ?? 0) > 0,
    modelsSectionComplete,
  ]
  const completeCount = sections.filter(Boolean).length

  const canSubmit = sections[0] && sections[1] && modelsSectionComplete

  const handleSubmit = () => {
    if (!canSubmit) return
    setSubmitting(true)
    // TODO: POST /api/applications (multipart, or JSON + uploads) — the
    // applicant (name, phone, dob, sex, face photo) + coverage + models_requested
    // + per-model declared_history (DATABASE.md §C); uploads keyed by
    // model_arm_id. The reference in the confirmation is the one the DATABASE
    // returns (applicants_ref_seq → external_ref), which may differ from any
    // client-side preview. Set it from the response before showing the alert.
    window.setTimeout(() => {
      setSubmitting(false)
      setSubmitted(true)
    }, 1200)
  }

  if (submitted) {
    return (
      <Stack gap="md" maw={560}>
        <Alert icon={<IconCircleCheck size={18} />} color="teal" title="Application submitted">
          <Text size="sm">
            Reference <Text span ff="monospace" fw={600}>{form.values.reference}</Text>{' '}
            is now in the queue as “Evaluation pending”.
          </Text>
        </Alert>
        <Button size="xs" onClick={() => { window.history.back() }}>
          Back to queue
        </Button>
      </Stack>
    )
  }

  return (
    <Stack gap="lg" maw={980}>
      {/* Sticky progress hint */}
      <Paper
        p="sm"
        pos="sticky"
        top={0}
        style={{ zIndex: 10 }}
        bd="1px solid var(--mantine-color-default-border)"
        bg="var(--mantine-color-body)"
      >
        <Group justify="space-between">
          <Text size="xs" c="dimmed">
            {completeCount} of 3 sections complete
          </Text>
          <Text size="xs" fw={600} c={canSubmit ? 'teal' : 'dimmed'}>
            {canSubmit ? 'Ready to submit' : 'Not ready to submit'}
          </Text>
        </Group>
      </Paper>

      <div>
        <Text size="xs" c="dimmed" tt="uppercase" fw={600} className="hl-eyebrow">
          New application
        </Text>
        <Text size="lg" fw={600}>
          Review a new client
        </Text>
        <Text size="sm" c="dimmed">
          Fill this out while the client is in front of you. Enter the client’s
          name and phone, add their face photo, pick the models that apply, and
          attach each one’s report in its panel. The reference is generated for
          you. One page, one submit.
        </Text>
      </div>

      {/* ── Section 1 · Applicant ─────────────────────────────── */}
      <Section n="1" title="Applicant" complete={sections[0]}>
        <TextInput
          label="Reference"
          description="Generated automatically by the database (HL-&lt;seq&gt;) — assigned at submit if not shown yet. Read-only."
          required
          readOnly
          placeholder="assigned on submit"
          {...form.getInputProps('reference')}
        />

        <SimpleGrid cols={{ base: 1, md: 2 }} spacing="lg" mt="md">
          <Stack gap="sm">
            <Group grow align="flex-start">
              <TextInput label="Name" required placeholder="Client name" {...form.getInputProps('name')} />
              <TextInput label="Phone" required placeholder="+880 1XXXXXXXXX" {...form.getInputProps('phone')} />
            </Group>
            <Group grow align="flex-start">
              <TextInput label="Date of birth" type="date" {...form.getInputProps('dob')} />
              <Select
                label="Sex"
                placeholder="Prefer not to say"
                data={['Female', 'Male', 'Other', 'Prefer not to say']}
                clearable
                {...form.getInputProps('sex')}
              />
            </Group>
          </Stack>

          <FacePhotoUpload
            file={facePhoto}
            preview={facePreview}
            note={rejectNote.face}
            onDrop={addFacePhoto}
            onReject={addFaceReject}
            onRemove={() => setFace(null)}
          />
        </SimpleGrid>
      </Section>

      <Divider my="xs" />

      {/* ── Section 2 · Coverage requested ─────────────────────── */}
      <Section n="2" title="Coverage requested" complete={sections[1]}>
        <Group align="flex-end">
          <Select
            label="Coverage type"
            placeholder="Select"
            required
            data={['Life', 'Health', 'Critical illness']}
            {...form.getInputProps('coverageType')}
          />
          <NumberInput
            label="Coverage amount (BDT)"
            placeholder="1,000,000"
            required
            thousandSeparator=","
            min={0}
            {...form.getInputProps('coverageAmount')}
          />
          <Select
            label="Policy term"
            placeholder="Years"
            data={['1', '5', '10', '20']}
            clearable
            {...form.getInputProps('policyTerm')}
          />
        </Group>
      </Section>

      <Divider my="xs" />

      {/* ── Section 3 · Models ─────────────────────────────────── */}
      <Section n="3" title="Models" complete={sections[2]}>
        <Text size="sm" c="dimmed">
          Click all that apply. Each model’s panel shows which report to upload
          and which questions it needs answered.
        </Text>

        <Group align="flex-start" wrap="nowrap" gap="lg">
          {/* Vertical menu */}
          <Stack gap={4} w={260} style={{ flexShrink: 0 }}>
            {MODELS.map((m) => {
              const on = form.values.selectedModels.includes(m.id)
              return (
                <Paper
                  key={m.id}
                  p="xs"
                  bd={on ? '1px solid var(--mantine-color-clinical-6)' : undefined}
                  withBorder={!on}
                  bg={on ? 'var(--mantine-color-clinical-0)' : 'transparent'}
                  style={{ cursor: 'pointer' }}
                  onClick={() => toggleModel(m.id)}
                >
                  <Checkbox
                    label={m.label}
                    description={m.modality}
                    checked={on}
                    readOnly
                    styles={{ label: { fontWeight: 600 } }}
                  />
                </Paper>
              )
            })}
          </Stack>

          {/* Pop-out panels for selected models */}
          <Stack gap="md" style={{ flex: 1, minWidth: 0 }}>
            {selected.length === 0 && (
              <Text size="sm" c="dimmed">
                Nothing selected yet — pick at least one model from the menu.
              </Text>
            )}
            {selected.map((m) => (
              <Paper key={m.id} bd="1px solid var(--mantine-color-default-border)" p="md">
                <Text fw={600} size="sm" mb="sm">
                  {m.label}
                  <Text span c="dimmed" fw={400}>
                    {' '}
                    · {m.modality}
                  </Text>
                </Text>

                {m.upload ? (
                  <PanelUpload
                    model={m}
                    files={modelFiles[m.id] ?? []}
                    note={rejectNote[m.id]}
                    onDrop={(files) => addModelFiles(m.id, files, m.upload!.category)}
                    onReject={(rejects) => addModelReject(m.id, rejects)}
                    onRemove={(id) => removeModelFile(m.id, id)}
                  />
                ) : (
                  <Alert color="gray" variant="light" mb="md">
                    <Text size="sm">No report needed — complete the demographic form.</Text>
                  </Alert>
                )}

                <ModelFieldControls
                  model={m}
                  values={form.values.modelFields[m.id] ?? {}}
                  setField={setField}
                  toggleSet={toggleSet}
                />
              </Paper>
            ))}
          </Stack>
        </Group>
      </Section>

      <Divider my="xs" />

      <Group justify="space-between" align="flex-start">
        <Text size="xs" c="dimmed" maw={420}>
          Disabled until the client’s name, phone and face photo are set, coverage type and
          amount are filled, at least one model is selected, and every required
          report is attached in its model’s panel.
        </Text>
        <Button size="sm" disabled={!canSubmit} loading={submitting} onClick={handleSubmit}>
          Submit application
        </Button>
      </Group>
      {submitting && (
        <Group gap="xs" c="dimmed">
          <Loader size={14} />
          <Text size="xs">Uploading evidence and creating the application…</Text>
        </Group>
      )}
    </Stack>
  )
}

function FacePhotoUpload({
  file,
  preview,
  note,
  onDrop,
  onReject,
  onRemove,
}: {
  file: File | null
  preview: string | null
  note: string | null
  onDrop: (files: File[]) => void
  onReject: (rejects: { file: File }[]) => void
  onRemove: () => void
}) {
  return (
    <Paper bd="1px solid var(--mantine-color-default-border)" p="md" mt="md">
      <Text fw={600} size="sm" mb="sm">
        Face photo{' '}
        <Text span c="red">
          *
        </Text>
      </Text>
      <Text size="xs" c="dimmed" mb="sm">
        For identification only, No model
        runs on this photo.
      </Text>

      {file && preview ? (
        <Group align="flex-start" gap="md">
          <Box
            w={96}
            h={96}
            style={{
              borderRadius: 6,
              overflow: 'hidden',
              border: '1px solid var(--mantine-color-default-border)',
              flexShrink: 0,
            }}
          >
            <img
              src={preview}
              alt="Face photo preview"
              style={{ width: '100%', height: '100%', objectFit: 'cover' }}
            />
          </Box>
          <Stack gap={4} align="flex-start">
            <Text ff="monospace" size="sm">
              {file.name}
            </Text>
            <Text size="xs" c="dimmed">
              {formatSize(file.size)}
            </Text>
            <Button size="xs" variant="subtle" color="red" onClick={onRemove}>
              Remove
            </Button>
          </Stack>
        </Group>
      ) : (
        <Dropzone
          accept={PHOTO}
          maxSize={MAX_FACE_BYTES}
          multiple={false}
          onDrop={onDrop}
          onReject={onReject}
        >
          <Group justify="center" py="md" style={{ pointerEvents: 'none' }}>
            <Text size="sm" c="dimmed">
              Drop the client’s face photo here, or click to browse — .png or
              .jpg, max 10 MB.
            </Text>
          </Group>
        </Dropzone>
      )}

      {note && (
        <Alert color="red" variant="light" icon={<IconAlertCircle size={16} />} mt="sm">
          <Text size="sm">{note}</Text>
        </Alert>
      )}
    </Paper>
  )
}

function PanelUpload({
  model,
  files,
  note,
  onDrop,
  onReject,
  onRemove,
}: {
  model: ModelDef
  files: EvidenceFile[]
  note: string | null
  onDrop: (files: File[]) => void
  onReject: (rejects: { file: File }[]) => void
  onRemove: (id: string) => void
}) {
  const upload = model.upload!
  return (
    <Box mb="md">
      <Alert icon={<IconFileUpload size={16} />} color="clinical" variant="light" mb="sm">
        <Text size="sm">
          Please submit: <Text span fw={600}>{upload.instruction}</Text>
        </Text>
      </Alert>

      <Dropzone
        accept={upload.accept}
        maxSize={MAX_FILE_BYTES}
        multiple
        onDrop={onDrop}
        onReject={onReject}
      >
        <Group justify="center" gap="xl" py="sm" style={{ pointerEvents: 'none' }}>
          <Dropzone.Accept>
            <IconFileUpload size={24} color="var(--mantine-color-clinical-5)" />
          </Dropzone.Accept>
          <Dropzone.Reject>
            <IconAlertCircle size={24} color="var(--mantine-color-red-5)" />
          </Dropzone.Reject>
          <Dropzone.Idle>
            <IconFileUpload size={24} color="var(--mantine-color-dimmed)" />
          </Dropzone.Idle>
          <Stack gap={2} align="center">
            <Text fw={500} size="sm">
              Drop files here or click to browse
            </Text>
            <Text size="xs" c="dimmed">
              {upload.instruction} · max 50 MB per file
            </Text>
          </Stack>
        </Group>
      </Dropzone>

      {note && (
        <Alert color="red" variant="light" icon={<IconAlertCircle size={16} />} mt="sm">
          <Text size="sm">{note}</Text>
        </Alert>
      )}

      {files.length > 0 && (
        <Table mt="sm">
          <Table.Thead>
            <Table.Tr>
              <Table.Th>File</Table.Th>
              <Table.Th>Size</Table.Th>
              <Table.Th w={60} />
            </Table.Tr>
          </Table.Thead>
          <Table.Tbody>
            {files.map((f) => (
              <Table.Tr key={f.id}>
                <Table.Td ff="monospace">{f.name}</Table.Td>
                <Table.Td>{formatSize(f.size)}</Table.Td>
                <Table.Td>
                  <ActionIcon
                    size="sm"
                    variant="subtle"
                    color="red"
                    aria-label="Remove file"
                    onClick={() => onRemove(f.id)}
                  >
                    <IconX size={14} />
                  </ActionIcon>
                </Table.Td>
              </Table.Tr>
            ))}
          </Table.Tbody>
        </Table>
      )}
    </Box>
  )
}

function ModelFieldControls({
  model,
  values,
  setField,
  toggleSet,
}: {
  model: ModelDef
  values: ModelValues
  setField: (modelId: string, key: string, value: Scalar) => void
  toggleSet: (modelId: string, key: string, value: string) => void
}) {
  if (model.id === 'cxr_lung') {
    return (
      <CxrPanel values={values} setField={setField} toggleSet={toggleSet} />
    )
  }

  if (model.fields.length === 0) {
    return (
      <Text size="xs" c="dimmed">
        No additional questions — the {model.label} model reads the uploaded report directly.
      </Text>
    )
  }

  return (
    <Stack gap="sm">
      {model.fields.map((f) => {
        if (f.kind === 'checkbox') {
          return (
            <Checkbox
              key={f.key}
              label={f.label}
              checked={bool(values[f.key])}
              onChange={(e) => setField(model.id, f.key, e.currentTarget.checked)}
            />
          )
        }
        if (f.kind === 'select') {
          return (
            <Select
              key={f.key}
              label={f.label}
              placeholder={f.placeholder ?? 'Select'}
              data={f.data}
              clearable
              value={typeof values[f.key] === 'string' ? (values[f.key] as string) : null}
              onChange={(v) => setField(model.id, f.key, v)}
            />
          )
        }
        return (
          <NumberInput
            key={f.key}
            label={f.label}
            description={f.description}
            min={0}
            value={typeof values[f.key] === 'number' ? (values[f.key] as number) : undefined}
            onChange={(v) => setField(model.id, f.key, v === '' ? null : v)}
          />
        )
      })}
    </Stack>
  )
}

function CxrPanel({
  values,
  setField,
  toggleSet,
}: {
  values: ModelValues
  setField: (modelId: string, key: string, value: Scalar) => void
  toggleSet: (modelId: string, key: string, value: string) => void
}) {
  const modelId = 'cxr_lung'
  const sym = (values.symptoms as string[]) ?? []
  const hist = (values.history as string[]) ?? []
  const cardio = (values.cardio as string[]) ?? []

  return (
    <Stack gap="md">
      {/* Current symptoms */}
      <Box>
        <Text fw={600} size="sm" mb="xs">
          Current symptoms
        </Text>
        <Stack gap="xs">
          {SYMPTOMS.map((s) => (
            <Checkbox
              key={s}
              label={s}
              checked={sym.includes(s)}
              onChange={() => toggleSet(modelId, 'symptoms', s)}
            />
          ))}
        </Stack>
      </Box>

      {/* TB history */}
      <Box>
        <Text fw={600} size="sm" mb="xs">
          Medical history
        </Text>
        <Stack gap="xs">
          <Checkbox
            label="Previously treated for TB"
            checked={bool(values.prior_tb)}
            onChange={(e) => {
              setField(modelId, 'prior_tb', e.currentTarget.checked)
              // Clear the follow-up when the parent is un-ticked, so a stale
              // answer cannot be submitted for someone with no TB history.
              if (!e.currentTarget.checked) {
                setField(modelId, 'prior_tb_treatment_completed', null)
              }
            }}
          />
          {bool(values.prior_tb) && (
            <Box pl="lg">
              {/*
                Yes/No rather than a checkbox. An unticked box cannot say whether
                the course was not completed or the question was never asked, and
                the two mean different things: a completed course lowers the score
                by 25, an incomplete one does not. Unanswered is sent as null and
                gated at submit rather than guessed.
              */}
              <Radio.Group
                label="Completed the full course of treatment"
                value={(values.prior_tb_treatment_completed as string) ?? ''}
                onChange={(v) => setField(modelId, 'prior_tb_treatment_completed', v)}
              >
                <Group gap="lg" mt={6}>
                  <Radio value="yes" label="Yes" />
                  <Radio value="no" label="No" />
                </Group>
              </Radio.Group>
            </Box>
          )}
          {HISTORY_ONCE.map((h) => (
            <Checkbox
              key={h}
              label={h}
              checked={hist.includes(h)}
              onChange={() => toggleSet(modelId, 'history', h)}
            />
          ))}
        </Stack>
      </Box>

      {/* Cardio */}
      <Box>
        <Text fw={600} size="sm" mb="xs">
          Cardiovascular
        </Text>
        <Stack gap="xs">
          {['Hypertension', 'High cholesterol', 'Family history of heart disease'].map((c) => (
            <Checkbox
              key={c}
              label={c}
              checked={cardio.includes(c)}
              onChange={() => toggleSet(modelId, 'cardio', c)}
            />
          ))}
        </Stack>
      </Box>
    </Stack>
  )
}
